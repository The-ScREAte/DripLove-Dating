
-- Create the av_profiles table to store user profile information
CREATE TABLE public.av_profiles (
  id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  name text,
  age integer,
  bio text,
  photos text[],
  location text,
  coordinates jsonb,
  interests text[]
);

-- Enable Row Level Security
ALTER TABLE public.av_profiles ENABLE ROW LEVEL SECURITY;

-- Policy: Authenticated users can view all profiles (for dating app functionality)
CREATE POLICY "Profiles are viewable by authenticated users."
  ON public.av_profiles FOR SELECT
  USING (auth.role() = 'authenticated');

-- Policy: Users can update their own profile
CREATE POLICY "Users can update their own profile."
  ON public.av_profiles FOR UPDATE
  USING (auth.uid() = id);

-- Policy: Users can insert their own profile
CREATE POLICY "Users can insert their own profile."
  ON public.av_profiles FOR INSERT
  WITH CHECK (auth.uid() = id);

-- Function to automatically create a profile for new users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.av_profiles (id, name)
  VALUES (new.id, new.raw_user_meta_data ->> 'full_name');
  RETURN new;
END;
$$;

-- Trigger to execute the function when a new user is created
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Create likes table for dating app functionality
CREATE TABLE public.av_likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    liker_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    liked_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    UNIQUE(liker_id, liked_id)
);

-- Enable RLS for av_likes
ALTER TABLE public.av_likes ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can insert their own likes."
  ON public.av_likes FOR INSERT
  WITH CHECK (auth.uid() = liker_id);

CREATE POLICY "Users can view their own likes and who liked them."
  ON public.av_likes FOR SELECT
  USING (auth.uid() = liker_id OR auth.uid() = liked_id);

-- Create matches table
CREATE TABLE public.av_matches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    user1_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    user2_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    UNIQUE(user1_id, user2_id)
);

-- Enable RLS for av_matches
ALTER TABLE public.av_matches ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own matches."
  ON public.av_matches FOR SELECT
  USING (auth.uid() = user1_id OR auth.uid() = user2_id);

-- Create blocks table
CREATE TABLE public.av_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    blocker_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    blocked_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    reason text,
    UNIQUE(blocker_id, blocked_id)
);

-- Enable RLS for av_blocks
ALTER TABLE public.av_blocks ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can insert their own blocks."
  ON public.av_blocks FOR INSERT
  WITH CHECK (auth.uid() = blocker_id);

CREATE POLICY "Users can view their own blocks."
  ON public.av_blocks FOR SELECT
  USING (auth.uid() = blocker_id);
;
