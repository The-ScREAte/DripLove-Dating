
-- Check if av_likes table exists, if not create it
CREATE TABLE IF NOT EXISTS public.av_likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    liker_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    liked_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    UNIQUE(liker_id, liked_id)
);

-- Enable RLS for av_likes if not already enabled
ALTER TABLE public.av_likes ENABLE ROW LEVEL SECURITY;

-- Create policies for av_likes (will skip if they already exist)
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'av_likes' AND policyname = 'Users can insert their own likes.') THEN
        CREATE POLICY "Users can insert their own likes."
          ON public.av_likes FOR INSERT
          WITH CHECK ( auth.uid() = liker_id );
    END IF;
END $$;

DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'av_likes' AND policyname = 'Users can view their own likes and who liked them.') THEN
        CREATE POLICY "Users can view their own likes and who liked them."
          ON public.av_likes FOR SELECT
          USING ( auth.uid() = liker_id OR auth.uid() = liked_id );
    END IF;
END $$;

