const localesDir = path.join(__dirname, 'src', 'i18n', 'locales');

['en', 'fr', 'de', 'zh', 'sw', 'pt', 'ar'].forEach(lang => {
  const filePath = path.join(localesDir, `${lang}.json`);
  const existingData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  
  const updatedData = deepMerge(existingData, registrationExtras[lang]);
  
  fs.writeFileSync(filePath, JSON.stringify(updatedData, null, 2), 'utf8');
  console.log(`✅ Updated ${lang}.json with extra registration translations`);
});

console.log('\n✨ All language files updated successfully!');
